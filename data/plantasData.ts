/**
 * Deriva o nível a partir do XP.
 *
 * Existe para que `nivel_atual` nunca precise ser guardado e mantido em sincronia
 * manualmente — antes desta função o mock trazia `xp: 240` com `nivel_atual: 2`,
 * combinação impossível na curva. XP é o único dado que precisa ser persistido.
 *
 * TETO (QA-04): satura no último nível da trilha. Qualquer XP a partir de
 * XP_MAXIMO devolve o Nível 8 — o acúmulo continua no dado, a progressão para
 * na trilha. XP negativo (por bug de chamada) é tratado como zero, para que o
 * nível nunca regrida por um sinal trocado.
 */
export function calcularNivel(xp: number) {
  const xpSeguro = Number.isFinite(xp) ? Math.max(0, xp) : 0;

  if (xpSeguro >= XP_MAXIMO) {
    return NIVEIS_EVOLUCAO[NIVEIS_EVOLUCAO.length - 1];
  }

  return (
    [...NIVEIS_EVOLUCAO].reverse().find((n) => xpSeguro >= n.xpMin) ?? NIVEIS_EVOLUCAO[0]
  );
}

